// Signing material lives in keystore.properties, which is git-ignored and points at a keystore
// kept outside the repo. Without it the release build still assembles, just unsigned, so a fresh
// clone is never broken by a missing secret. Note: storeFile must use forward slashes - a
// .properties file treats a backslash as an escape character and would silently mangle the path.
val keystoreProperties = Properties().apply {
    val file = rootProject.file("keystore.properties")
    if (file.exists()) file.inputStream().use { load(it) }
}

android {
    namespace = "com.glucarb"
    compileSdk = 36

    defaultConfig {
        // Permanent Play Store identity - can never be changed after the first upload.
        // Kept distinct from `namespace` (the Kotlin package) on purpose.
        applicationId = "io.github.overmeulen.glucarb"
        minSdk = 26
        targetSdk = 36
        versionCode = 3
        versionName = "1.1"
        testInstrumentationRunner = "androidx.test.runner.AndroidJUnitRunner"
    }

    signingConfigs {
        if (keystoreProperties.containsKey("storeFile")) {
            create("release") {
                storeFile = file(keystoreProperties.getProperty("storeFile"))
                storePassword = keystoreProperties.getProperty("storePassword")
                keyAlias = keystoreProperties.getProperty("keyAlias")
                keyPassword = keystoreProperties.getProperty("keyPassword")
                // v3 carries the proof-of-rotation record, so the signing key can be replaced
                // later without forcing an uninstall. v1 is dead weight above minSdk 24.
                enableV1Signing = false
                enableV2Signing = true
                enableV3Signing = true
            }
        }
    }

    buildTypes {
        release {
            isMinifyEnabled = true
            isShrinkResources = true
            proguardFiles(getDefaultProguardFile("proguard-android-optimize.txt"), "proguard-rules.pro")
            signingConfig = signingConfigs.findByName("release")
        }
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }

    kotlinOptions {
        jvmTarget = "17"
    }

    buildFeatures {
        compose = true
    }

    packaging {
        resources {
            excludes += "/META-INF/{AL2.0,LGPL2.1}"
        }
    }

    testOptions {
        unitTests {
            // Robolectric needs the merged manifest and resources to boot an Application.
            isIncludeAndroidResources = true
        }
    }
}

